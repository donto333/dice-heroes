def parse(art: str) -> list[str]:
    rows = [line for line in art.strip("\n").split("\n")]
    rows = [row.ljust(16, ".")[:16] for row in rows]
    while len(rows) < 16:
        rows.append("." * 16)
    return rows[:16]


def render(rows: list[str]) -> Image.Image:
    size = 18
    image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    filled = [[False] * size for _ in range(size)]
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            if char in PALETTE:
                image.putpixel((x + 1, y + 1), PALETTE[char])
                filled[y + 1][x + 1] = True
    # 빈 칸 중 그림과 맞닿은 곳에 테두리를 두른다.
    outline = PALETTE["k"]
    for y in range(size):
        for x in range(size):
            if filled[y][x]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < size and 0 <= ny < size and filled[ny][nx]:
                    image.putpixel((x, y), outline)
                    break
    return image


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, art in ICONS.items():
        render(parse(art)).save(OUT / f"{name}.png")
    print(f"{len(ICONS)}개 아이콘을 {OUT}에 저장했습니다.")


if __name__ == "__main__":
    main()
